#!/usr/bin/env bash
# shellcheck source-path=SCRIPTDIR
#
# bootstrap-route-reflector.sh - prepare an AlmaLinux 10 / Oracle Linux 10 VM
# as the GoBGP l2vpn-evpn route reflector of the Snout lab
# (spec: docs/workflows/phase_1.txt, section R).
#
# Copy the whole misc/ directory to the VM and run as root:
#   bash misc/bootstrap-route-reflector.sh --env misc/lab/rr.env

set -Eeuo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
SCRIPT_NAME=$(basename "${BASH_SOURCE[0]}")
# shellcheck source=lib/lab-common.sh
. "$SCRIPT_DIR/lib/lab-common.sh"

ADDRESS=${ADDRESS:-}
OPTION_VARS=(UPLINK_IF ADDRESS HOST_NAME ASN ROUTER_ID CLUSTER_ID GOBGP_VERSION QA_USER QA_PASSWORD QA_SSH_KEY)

usage() {
	cat <<EOF
Usage: $SCRIPT_NAME [--env FILE] [options]

Required environment variables (or lines in --env FILE):
  NEIGH1_IP, NEIGH2_IP, NEIGH3_IP   underlay IPs of the three hypervisors
  UPLINK_IF                         lab vNIC (must not carry the default route)
  ADDRESS                           static lab address, e.g. 172.31.0.10/24

Options (also accepted as environment variables, e.g. --cluster-id = CLUSTER_ID):
  --env FILE             load KEY=VALUE lines from FILE first
  --uplink-if NAME       lab vNIC
  --address CIDR         static lab address
  --host-name NAME       set the hostname
  --asn N                iBGP AS number (default: 65000)
  --router-id IP         BGP router ID (default: lab address)
  --cluster-id IP        route reflector cluster ID (default: router ID)
  --gobgp-version VER    GoBGP release or "latest" (default: latest)
  --qa-user NAME         sudo user (default: QA)
  --qa-password PASS     password of the QA user
  --qa-ssh-key KEY|FILE  authorized SSH key of the QA user
  -h, --help             show this help
EOF
}

validate() {
	require_root
	require_supported_os
	require_env NEIGH1_IP NEIGH2_IP NEIGH3_IP UPLINK_IF ADDRESS
	ASN=${ASN:-65000}
	GOBGP_VERSION=${GOBGP_VERSION:-latest}

	is_ipv4_cidr "$ADDRESS" || die "ADDRESS must be IPv4 CIDR, got '$ADDRESS'"
	ADDRESS_IP=${ADDRESS%/*}
	validate_peer_ips "$ADDRESS_IP" "$ADDRESS" NEIGH1_IP NEIGH2_IP NEIGH3_IP
	validate_lab_iface UPLINK_IF "$UPLINK_IF"

	ROUTER_ID=${ROUTER_ID:-$ADDRESS_IP}
	CLUSTER_ID=${CLUSTER_ID:-$ROUTER_ID}
	is_ipv4 "$ROUTER_ID" || die "ROUTER_ID must be an IPv4 address, got '$ROUTER_ID'"
	is_ipv4 "$CLUSTER_ID" || die "CLUSTER_ID must be an IPv4 address, got '$CLUSTER_ID'"
	if ! is_uint "$ASN" || ((ASN < 1 || ASN > 4294967295)); then
		die "ASN must be 1-4294967295, got '$ASN'"
	fi
}

gobgp_config() {
	local neighbor
	cat <<EOF
# Generated by $SCRIPT_NAME - Snout lab route reflector
[global.config]
  as = $ASN
  router-id = "$ROUTER_ID"

# All Snout hypervisors are iBGP route reflector clients for l2vpn-evpn.
[[peer-groups]]
  [peer-groups.config]
    peer-group-name = "hypervisors"
    peer-as = $ASN
  [peer-groups.route-reflector.config]
    route-reflector-client = true
    route-reflector-cluster-id = "$CLUSTER_ID"
  [peer-groups.timers.config]
    connect-retry = 5
  [[peer-groups.afi-safis]]
    [peer-groups.afi-safis.config]
      afi-safi-name = "l2vpn-evpn"
EOF
	for neighbor in "$NEIGH1_IP" "$NEIGH2_IP" "$NEIGH3_IP"; do
		cat <<EOF

[[neighbors]]
  [neighbors.config]
    neighbor-address = "$neighbor"
    peer-group = "hypervisors"
  [neighbors.transport.config]
    local-address = "$ADDRESS_IP"
EOF
	done
}

summary() {
	echo
	log "Route reflector bootstrap finished"
	cat <<EOF
  Lab NIC       : $UPLINK_IF $ADDRESS
  GoBGP         : $GOBGP_VERSION, AS $ASN, router-id $ROUTER_ID, cluster-id $CLUSTER_ID
  Clients       : $NEIGH1_IP, $NEIGH2_IP, $NEIGH3_IP
  QA user       : ${QA_USER:-QA} (NOPASSWD sudo)

Useful commands:
  gobgp neighbor                 # sessions with the hypervisors
  gobgp global rib -a evpn       # reflected EVPN routes
EOF
}

main() {
	trap 'die "command failed at line $LINENO: $BASH_COMMAND"' ERR
	parse_options "${OPTION_VARS[@]}" -- "$@"
	validate
	set_hostname
	setup_qa_user
	disable_firewall
	log "Installing tools"
	dnf -y -q install curl tar iproute tcpdump
	install_gobgp
	gobgp_config | install_gobgp_config
	configure_underlay "$UPLINK_IF" "$ADDRESS"
	start_gobgp
	summary
}

if [[ ${BASH_SOURCE[0]} == "$0" ]]; then
	main "$@"
fi
